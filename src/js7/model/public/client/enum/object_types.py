    INCLUDESCRIPT = "INCLUDESCRIPT"
    REPORT = "REPORT"
    DEPLOYMENTDESCRIPTOR = "DEPLOYMENTDESCRIPTOR"
    DESCRIPTORFOLDER = "DESCRIPTORFOLDER"


