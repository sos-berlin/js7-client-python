    WORKFLOW = "WORKFLOW"
    LOCK = "LOCK"
    NOTICEBOARD = "NOTICEBOARD"
    JOBRESOURCE = "JOBRESOURCE"
    FILEORDERSOURCE = "FILEORDERSOURCE"
    SCHEDULE = "SCHEDULE"
    WORKINGDAYSCALENDAR = "WORKINGDAYSCALENDAR"
    NONWORKINGDAYSCALENDAR = "NONWORKINGDAYSCALENDAR"
